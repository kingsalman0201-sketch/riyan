export const isMainCropOfLocation = (cropName, state, city) => {
  const cityCrops = cityMainCrops[city];
  const stateCrops = stateMainCrops[state] || [];
  
  // If city specific override exists, use it. Otherwise, use state level crops.
  const crops = (cityCrops && cityCrops.length > 0) ? cityCrops : stateCrops;
  const nameLower = String(cropName).toLowerCase();
  
  return crops.some(crop => {
    const cropLower = crop.toLowerCase();
    
    // Check if exactly equal
    if (nameLower === cropLower) return true;
    
    // Check if one contains the other
    if (nameLower.includes(cropLower) || cropLower.includes(nameLower)) return true;
    
    // Special check for rice / paddy
    const isRiceA = nameLower.includes("rice") || nameLower.includes("paddy");
    const isRiceB = cropLower.includes("rice") || cropLower.includes("paddy");
    if (isRiceA && isRiceB) return true;
    
    // Special check for tur / arhar / toor dal / arhar / toordal
    const isTurA = nameLower.includes("tur") || nameLower.includes("toor") || nameLower.includes("arhar") || nameLower.includes("toordal");
    const isTurB = cropLower.includes("tur") || cropLower.includes("toor") || cropLower.includes("arhar") || cropLower.includes("toordal");
    if (isTurA && isTurB) return true;
    
    return false;
  });
};

export const getLocationCropPriority = (cropName, state, city) => {
  const cityCrops = cityMainCrops[city];
  const stateCrops = stateMainCrops[state] || [];
  
  const nameLower = String(cropName).toLowerCase();
  
  const matchesCrop = (item, name) => {
    const itemLower = item.toLowerCase();
    const nameLowerStr = name.toLowerCase();
    if (itemLower === nameLowerStr) return true;
    if (itemLower.includes(nameLowerStr) || nameLowerStr.includes(itemLower)) return true;
    
    // Rice / Paddy check
    const isRiceA = itemLower.includes("rice") || itemLower.includes("paddy");
    const isRiceB = nameLowerStr.includes("rice") || nameLowerStr.includes("paddy");
    if (isRiceA && isRiceB) return true;
    
    // Tur / Arhar / Toor check
    const isTurA = itemLower.includes("tur") || itemLower.includes("toor") || itemLower.includes("arhar") || itemLower.includes("toordal");
    const isTurB = nameLowerStr.includes("tur") || nameLowerStr.includes("toor") || nameLowerStr.includes("arhar") || nameLowerStr.includes("toordal");
    if (isTurA && isTurB) return true;
    
    return false;
  };

  if (cityCrops && cityCrops.length > 0) {
    const cityIndex = cityCrops.findIndex(crop => matchesCrop(crop, nameLower));
    if (cityIndex !== -1) {
      return cityIndex; // Priority 0, 1, 2...
    }
  }

  const stateIndex = stateCrops.findIndex(crop => matchesCrop(crop, nameLower));
  if (stateIndex !== -1) {
    return 100 + stateIndex; // Priority 100, 101, 102...
  }

  return 1000; // Low priority
};

